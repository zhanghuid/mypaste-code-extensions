#!/usr/bin/env node
/**
 * Builds each surface package's page.
 *
 * A surface package ships one HTML page plus one bundled script. The template
 * (src/preview.html) holds the markup and the styles and marks where the
 * script goes with `<!--bundle-->`; this script bundles src/main.ts into a
 * single IIFE and puts it there. No module loader, no second file: the host
 * serves exactly the bytes the archive contains, and the page talks to the
 * host only through its own bridge.
 *
 * Usage:
 *   node scripts/build-surfaces.mjs --all
 *   node scripts/build-surfaces.mjs --package com.mypaste.code-card --out FILE
 */

import { build } from "esbuild";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const plugins = path.join(root, "plugins");
const PLACEHOLDER = "<!--bundle-->";
/** The host's surface-document ceiling (D-1091); a larger page is refused. */
const MAX_DOCUMENT_BYTES = 1 << 20;

function fail(message) {
  process.stderr.write(`build-surfaces: ${message}\n`);
  process.exit(1);
}

function parseArgs(argv) {
  const options = { all: false, packageId: "", out: "" };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--all") options.all = true;
    else if (arg === "--package") options.packageId = argv[++index] ?? "";
    else if (arg === "--out") options.out = argv[++index] ?? "";
    else fail(`无法识别的参数 ${arg}`);
  }
  return options;
}

async function surfacePackages() {
  const entries = await readdir(plugins, { withFileTypes: true });
  const found = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const template = path.join(plugins, entry.name, "src", "preview.html");
    try {
      await readFile(template);
      found.push(entry.name);
    } catch {
      // A package without a surface template is a run-script or binary
      // package; this build has nothing to do for it.
    }
  }
  return found.sort();
}

async function bundle(packageId) {
  const directory = path.join(plugins, packageId);
  const entry = path.join(directory, "src", "main.ts");
  const template = await readFile(path.join(directory, "src", "preview.html"), "utf8");
  if (template.split(PLACEHOLDER).length !== 2) {
    fail(`${packageId} 的 src/preview.html 必须恰好包含一个 ${PLACEHOLDER}`);
  }
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: "iife",
    target: "es2022",
    minify: true,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  const script = result.outputFiles[0]?.text;
  if (!script) fail(`${packageId} 没有产出脚本`);
  // The replacement is a function so `$` sequences in the bundle stay literal.
  const header =
    "<!-- Generated by scripts/build-surfaces.mjs from src/preview.html. " +
    "Edit the sources, not this file. -->\n";
  const document = header + template.replace(PLACEHOLDER, () => script);
  const bytes = Buffer.byteLength(document);
  if (bytes > MAX_DOCUMENT_BYTES) {
    fail(`${packageId} 的表面页面 ${bytes} 字节，超过 ${MAX_DOCUMENT_BYTES} 字节上限`);
  }
  return { packageId, directory, document, bytes };
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.all && options.packageId) fail("--all 与 --package 只能选一个");
  const packages = options.packageId
    ? [options.packageId]
    : await surfacePackages();
  if (packages.length === 0) fail("没有找到任何表面包");
  if (options.out && packages.length !== 1) fail("--out 只能配一个 --package");

  for (const packageId of packages) {
    const built = await bundle(packageId);
    const out = options.out ? path.resolve(options.out) : path.join(built.directory, "preview.html");
    await writeFile(out, built.document);
    process.stdout.write(`${packageId}: ${built.bytes} 字节 → ${path.relative(root, out)}\n`);
  }
}

main().catch((error) => fail(error instanceof Error ? error.message : String(error)));
